// Explicit read-only import from the original app. No runtime sibling dependency.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const app = path.resolve(__dirname, '..');
const source = path.resolve(app, '../9-learning-angles');
// Only normalize source line endings; content and all original files stay unchanged.
const data = Buffer.from(fs.readFileSync(path.join(source, 'data.js'),'utf8').replace(/\r\n/g,'\n'));
const hash = crypto.createHash('sha256').update(data).digest('hex');
const outputs = new Map([['quiz-data.js', Buffer.concat([
  Buffer.from('// Generated by scripts/sync-quiz.cjs from 9-learning-angles/data.js\n// Source SHA-256: '+hash+'\n'), data
])]]);
for (const name of fs.readdirSync(path.join(source, 'assets/characters'))) {
  outputs.set('assets/characters/'+name, fs.readFileSync(path.join(source, 'assets/characters', name)));
}
for (const name of ['Kanit-Regular.ttf', 'Kanit-SemiBold.ttf']) {
  outputs.set('assets/fonts/'+name, fs.readFileSync(path.join(source, 'assets/fonts', name)));
}
const check = process.argv.includes('--check');
let failures = 0;
for (const [name, content] of outputs) {
  const target = path.join(app, name);
  if (check) {
    if (!fs.existsSync(target) || !fs.readFileSync(target).equals(content)) {
      console.error('Snapshot differs: '+name); failures++;
    }
  } else {
    fs.mkdirSync(path.dirname(target), {recursive:true});
    fs.writeFileSync(target, content);
  }
}
if (failures) process.exitCode = 1;
else console.log((check?'Verified':'Imported')+' original quiz and '+(outputs.size-1)+' existing assets; SHA-256 '+hash);
