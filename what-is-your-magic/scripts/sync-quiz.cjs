// Explicit read-only import from the original app. No runtime sibling dependency.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const app = path.resolve(__dirname, '..');
const source = path.resolve(app, '../9-learning-angles');
// Only normalize source line endings; content and all original files stay unchanged.
const data = Buffer.from(fs.readFileSync(path.join(source, 'data.js'),'utf8').replace(/\r\n/g,'\n'));
const hash = crypto.createHash('sha256').update(data).digest('hex');
// Chief-approved wording override for YourMagic only (7 November 2026).
// Original app, move=creator and question weight remain unchanged.
const previous='เอาไปต่อยอดคิดเป็นไอเดียใหม่ของตัวเอง';
const revised='ลองจำลองสถานการณ์ในหัว เพื่อช่วยให้เข้าใจเรื่องนั้นมากขึ้น';
if(data.toString('utf8').split(previous).length!==2)throw Error('Expected exactly one source option for the wording override');
const appData=Buffer.from(data.toString('utf8').replace(previous,revised));
const outputs = new Map([['quiz-data.js', Buffer.concat([
  Buffer.from('// Generated by scripts/sync-quiz.cjs from 9-learning-angles/data.js\n// Source SHA-256: '+hash+'\n// YourMagic-only wording: mental simulation option, approved 2026-11-07; original scores unchanged.\n'), appData
])]]);
for (const name of fs.readdirSync(path.join(source, 'assets/characters'))) {
  outputs.set('assets/characters/'+name, fs.readFileSync(path.join(source, 'assets/characters', name)));
}
for (const name of ['Kanit-Regular.ttf', 'Kanit-SemiBold.ttf']) {
  outputs.set('assets/fonts/'+name, fs.readFileSync(path.join(source, 'assets/fonts', name)));
}
const check = process.argv.includes('--check');
let failures = 0;
for (const [name, content] of outputs) {
  const target = path.join(app, name);
  if (check) {
    if (!fs.existsSync(target) || !fs.readFileSync(target).equals(content)) {
      console.error('Snapshot differs: '+name); failures++;
    }
  } else {
    fs.mkdirSync(path.dirname(target), {recursive:true});
    fs.writeFileSync(target, content);
  }
}
if (failures) process.exitCode = 1;
else console.log((check?'Verified':'Imported')+' source quiz with approved YourMagic wording override and '+(outputs.size-1)+' existing assets; SHA-256 '+hash);
